// Package site models the data file the page reads and keeps it consistent.
//
// The page loads data/listings.js as a plain script that assigns
// window.OLMACS_DATA. That is deliberate: a .json file fetched with fetch() is
// blocked by CORS under file://, so the page would stop working when opened by
// double-clicking it. A script tag works over both file:// and https.
package site

import (
	"encoding/json"
	"fmt"
	"os"
	"path/filepath"
	"sort"
	"strconv"
	"strings"
)

// Listing is one card on the page. Field names match the keys the page reads.
type Listing struct {
	ID          int64   `json:"id"`
	OID         string  `json:"oid"`
	Title       string  `json:"title"`
	URL         string  `json:"url"`
	Kind        string  `json:"kind"`
	Chip        string  `json:"chip"`
	Gen         string  `json:"gen"`
	RAM         int     `json:"ram"`
	RAMStated   bool    `json:"ram_stated"`
	RAMEvidence string  `json:"ram_evidence"`
	Price       float64 `json:"price"`
	PriceWas    float64 `json:"price_was,omitempty"`
	PriceLabel  string  `json:"price_label"`
	Currency    string  `json:"currency"`
	RON         int     `json:"ron"`
	City        string  `json:"city"`
	Region      string  `json:"region"`
	Business    bool    `json:"business"`
	Created     string  `json:"created"`
	Refreshed   string  `json:"refreshed"`
	Desc        string  `json:"desc"`

	BelowThreshold bool   `json:"below_threshold"`
	Status         string `json:"status"`       // live | new | gone
	FacetStatus    string `json:"facet_status"` // available | available,new | gone
	GoneReason     string `json:"gone_reason"`  // sold | reused | ""
	Note           string `json:"note"`
	FirstSeen      string `json:"first_seen"`
}

// Snapshot is the reduced view of one sweep the over-time charts read.
type Snapshot struct {
	OID  string `json:"oid"`
	Kind string `json:"kind"`
	Gen  string `json:"gen"`
	RAM  int    `json:"ram"`
	City string `json:"city"`
	RON  int    `json:"ron"`
}

type Sweep struct {
	Date  string     `json:"date"`
	ISO   string     `json:"iso"`
	Offer []Snapshot `json:"offer"`
}

type Summary struct {
	Total        int            `json:"total"`
	Available    int            `json:"available"`
	Sold         int            `json:"sold"`
	Fresh        int            `json:"fresh"`
	Min          int            `json:"min"`
	Max          int            `json:"max"`
	Cities       int            `json:"cities"`
	EURRON       float64        `json:"eur_ron"`
	EURRONSource string         `json:"eur_ron_source"`
	Checked      string         `json:"checked"`
	Prev         string         `json:"prev"`
	Built        string         `json:"built"`
	Undated      int            `json:"undated"`
	SoldSince    int            `json:"sold_since"`
	ByGen        map[string]int `json:"by_gen"`
	ByRAM        map[string]int `json:"by_ram"`
	ByKind       map[string]int `json:"by_kind"`
	ByCity       map[string]int `json:"by_city"`
	ByStatus     map[string]int `json:"by_status"`
}

type Dataset struct {
	Main    []Listing `json:"main"`
	Minis   []Listing `json:"minis"`
	Sweeps  []Sweep   `json:"sweeps"`
	Summary Summary   `json:"summary"`
}

const header = `// Generated by ` + "`go run ./cmd/olmacs sweep`" + ` — do not edit by hand.
// Curated per-listing notes live in data/notes.json and are merged in on each run.
window.OLMACS_DATA = `

// Load reads data/listings.js back into a Dataset.
func Load(path string) (*Dataset, error) {
	raw, err := os.ReadFile(path)
	if err != nil {
		return nil, err
	}
	s := string(raw)
	i := strings.Index(s, "window.OLMACS_DATA = ")
	if i < 0 {
		return nil, fmt.Errorf("%s: no window.OLMACS_DATA assignment", path)
	}
	body := strings.TrimSpace(s[i+len("window.OLMACS_DATA = "):])
	body = strings.TrimSuffix(strings.TrimSpace(body), ";")

	var d Dataset
	if err := json.Unmarshal([]byte(body), &d); err != nil {
		return nil, fmt.Errorf("%s: %w", path, err)
	}
	return &d, nil
}

// Save writes the data file. Output is indented so a sweep produces a diff a
// human can actually read in a pull request.
func (d *Dataset) Save(path string) error {
	body, err := json.MarshalIndent(d, "", " ")
	if err != nil {
		return err
	}
	if err := os.MkdirAll(filepath.Dir(path), 0o755); err != nil {
		return err
	}
	return os.WriteFile(path, []byte(header+string(body)+";\n"), 0o644)
}

// All returns every listing, laptops and minis together.
func (d *Dataset) All() []Listing { return append(append([]Listing{}, d.Main...), d.Minis...) }

// Recompute derives the summary from the listings. Nothing in the page is
// hand-counted, so a miscount here is the only way the header can lie.
func (d *Dataset) Recompute(checked, prev string, eurRon float64, eurSource string) {
	all := d.All()
	s := Summary{
		Checked: checked, Prev: prev, Built: d.Summary.Built,
		EURRON: eurRon, EURRONSource: eurSource,
		ByGen: map[string]int{}, ByRAM: map[string]int{}, ByKind: map[string]int{},
		ByCity: map[string]int{}, ByStatus: map[string]int{},
	}
	if s.Built == "" {
		s.Built = checked
	}
	minRON, maxRON := 0, 0
	for _, l := range all {
		s.ByGen[l.Gen]++
		s.ByRAM[strconv.Itoa(l.RAM)]++
		s.ByKind[l.Kind]++
		s.ByCity[l.City]++
		switch l.Status {
		case "gone":
			s.Sold++
		case "new":
			s.Fresh++
		}
		if l.Status != "gone" {
			s.Available++
			if minRON == 0 || l.RON < minRON {
				minRON = l.RON
			}
			if l.RON > maxRON {
				maxRON = l.RON
			}
			if l.Created == "" || l.Created < "2023-01-01" {
				s.Undated++
			}
		}
	}
	s.Total, s.Min, s.Max, s.Cities = len(all), minRON, maxRON, len(s.ByCity)
	s.ByStatus["available"], s.ByStatus["new"], s.ByStatus["gone"] = s.Available, s.Fresh, s.Sold

	// how many machines that were on offer at the previous sweep have since gone
	if n := len(d.Sweeps); n >= 2 {
		was := map[string]bool{}
		for _, o := range d.Sweeps[n-2].Offer {
			was[o.OID] = true
		}
		for _, l := range all {
			if l.Status == "gone" && was[l.OID] {
				s.SoldSince++
			}
		}
	}
	d.Summary = s
}

// AppendSweep records the machines on offer right now as a checkpoint.
func (d *Dataset) AppendSweep(date, iso string) {
	var offer []Snapshot
	for _, l := range d.All() {
		if l.Status == "gone" {
			continue
		}
		offer = append(offer, Snapshot{l.OID, l.Kind, l.Gen, l.RAM, l.City, l.RON})
	}
	sort.Slice(offer, func(i, j int) bool { return offer[i].OID < offer[j].OID })

	// re-running on the same day replaces that day's checkpoint rather than
	// stacking duplicates
	if n := len(d.Sweeps); n > 0 && d.Sweeps[n-1].ISO == iso {
		d.Sweeps[n-1] = Sweep{date, iso, offer}
		return
	}
	d.Sweeps = append(d.Sweeps, Sweep{date, iso, offer})
}

// LoadNotes reads the hand-maintained note overrides, keyed by OID.
func LoadNotes(path string) (map[string]string, error) {
	raw, err := os.ReadFile(path)
	if os.IsNotExist(err) {
		return map[string]string{}, nil
	}
	if err != nil {
		return nil, err
	}
	notes := map[string]string{}
	return notes, json.Unmarshal(raw, &notes)
}
